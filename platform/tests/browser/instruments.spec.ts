import {test,expect} from '@playwright/test';
const backend=process.env.TEST_API_URL||'http://127.0.0.1:8787';
const admin=process.env.ADMIN_TOKEN||'local-test-admin-not-for-production';
test('organizer creates three instruments then edits names prices icons and supply before start',async({page,request},info)=>{
 const id=`assets-ui-${info.project.name}-${Date.now()}`;
 await page.goto('/?view=admin');await page.getByLabel('组织者管理凭证').fill(admin);
 const create=page.locator('section').filter({has:page.getByRole('heading',{name:'创建多标的比赛',exact:true})});
 await create.getByLabel('比赛名称',{exact:true}).fill('可配置标的界面测试');await create.getByLabel('比赛编号',{exact:true}).fill(id);
 const fields=create.locator('.instrument-settings');
 const first=fields.locator('.instrument-settings-card').nth(0);
 await first.getByLabel('标的名称',{exact:true}).fill('星际资产');await first.getByLabel('交易代码',{exact:true}).fill('STAR');
 await first.getByLabel('初始价格（DUSD）',{exact:true}).fill('25.50');await first.getByLabel('图标（emoji 或 HTTPS 图片地址）',{exact:true}).fill('🚀');
 const second=fields.locator('.instrument-settings-card').nth(1);
 await second.getByLabel('标的名称',{exact:true}).fill('海洋资产');await second.getByLabel('交易代码',{exact:true}).fill('OCEAN');
 await second.getByLabel('初始价格（DUSD）',{exact:true}).fill('61.00');
 await fields.getByRole('button',{name:'添加标的',exact:true}).click();
 const third=fields.locator('.instrument-settings-card').nth(2);
 await third.getByLabel('标的名称',{exact:true}).fill('绿洲资产');await third.getByLabel('交易代码',{exact:true}).fill('OASIS');
 await create.getByLabel('初始现金（DUSD）',{exact:true}).fill('3456.78');
 await create.getByLabel('星际资产 初始数量（份）',{exact:true}).fill('10');
 await create.getByLabel('海洋资产 初始数量（份）',{exact:true}).fill('20');
 await create.getByLabel('绿洲资产 初始数量（份）',{exact:true}).fill('30');
 await create.getByLabel('练习赛',{exact:false}).check();await create.getByRole('button',{name:'创建比赛',exact:true}).click();
 await expect(page.getByLabel('当前比赛',{exact:true})).toHaveValue(id);
 const joined=await(await request.post(`${backend}/api/markets/${id}/join`,{data:{name:'Custom UI Agent'}})).json();
 expect(joined.account.holdings).toEqual({STAR:10,OCEAN:20,OASIS:30});
 const editor=page.getByRole('form',{name:'配置本场交易标的'});
 const editFirst=editor.locator('.instrument-settings-card').nth(0);
 await editFirst.getByLabel('标的名称',{exact:true}).fill('星际资产（调整）');await editFirst.getByLabel('初始价格（DUSD）',{exact:true}).fill('18.75');
 await editFirst.getByLabel('图标（emoji 或 HTTPS 图片地址）',{exact:true}).fill('🌠');
 await editor.getByRole('button',{name:'删除标的 3',exact:true}).click();await editor.getByRole('button',{name:'保存标的设置',exact:true}).click();
 await expect(editor.getByRole('status')).toHaveText('标的设置已保存。');
 const snapshot=await(await request.get(`${backend}/api/markets/${id}`)).json();
 expect(snapshot.instruments).toHaveLength(2);expect(snapshot.instruments[0]).toMatchObject({name:'星际资产（调整）',reference:1875,icon:'🌠'});
 expect(snapshot.initialEquity).toBe(345678+10*1875+20*6100);
 const account=await(await request.get(`${backend}/api/markets/${id}/account`,{headers:{Authorization:`Bearer ${joined.apiKey}`}})).json();
 expect(account.holdings).toEqual({STAR:10,OCEAN:20});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await editor.screenshot({path:`reports/instrument-settings-${info.project.name}.png`});
 await page.goto(`/?market=${id}`);
 await expect(page.locator('.instrument-heading')).toContainText('星际资产（调整）');
 await expect(page.locator('.instrument-heading .asset-icon')).toHaveText('🌠');
 await expect(page.getByRole('button',{name:/海洋资产 暂无成交/})).toBeVisible();
});

test('HTTPS instrument icons render and failed images fall back to the name',async({page,request},info)=>{
 const id=`icon-ui-${info.project.name}-${Date.now()}`;
 const good='https://icons.example.test/logo.svg',bad='https://icons.example.test/missing.svg';
 const item={symbol:'ICON',name:'图标资产',initialPrice:4000,icon:good};
 const created=await request.post(`${backend}/api/admin/markets`,{headers:{Authorization:`Bearer ${admin}`},data:{id,name:'图标测试',practice:true,assetMode:'ai',instruments:[item]}});
 expect(created.status()).toBe(201);
 await page.route(good,r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><circle cx="16" cy="16" r="14" fill="#34754d"/></svg>'}));
 await page.goto(`/?market=${id}`);
 await expect(page.locator('.instrument-heading .asset-icon img')).toBeVisible();
 await expect.poll(()=>page.locator('.instrument-heading .asset-icon img').evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBe(true);
 await request.post(`${backend}/api/admin/markets/${id}/instruments`,{headers:{Authorization:`Bearer ${admin}`},data:[{...item,icon:bad}]});
 await page.route(bad,r=>r.abort());await page.reload();
 await expect(page.locator('.instrument-heading .asset-icon')).toHaveText('图');
 await expect(page.locator('.instrument-heading .asset-icon img')).toHaveCount(0);
});
